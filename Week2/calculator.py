weight = float(input("How many kilos does the product weight? "))
price = float(input("What's the kilo price? "))

sum = weight + price
print(f"The sum is {sum}")

difference = weight - price
print(f"The difference is {difference}")

product = weight * price
print(f"The product is {product}")

division = weight / price
print(f"The division is {division}")

